#!/usr/bin/env python3
"""V14 stage S11′: generate `Z3Net/TDBal.lean`, the balance on the full steps of `thm:D` (the 32 full steps written
out, so that `linarith` sees `2 dr(E)` as linear forms in the entries). Usage (from the repository root):
uv run --no-project python scripts/gen_tdbal.py"""
import itertools
import os

L = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
HEADER = open(os.path.join(L, 'Z3Net', 'TDCert.lean')).read().split('module\n')[0]
FULL = list(itertools.product((1, -1), repeat=5))
NORM = 'simp only [Fin.zero_eta, Fin.mk_one, Fin.reduceFinMk, Fin.isValue] at *'


def vec(e):
    return '![' + ', '.join(str(x) for x in e) + ']'


def form(e):
    terms = []
    for c in range(5):
        for d in range(5):
            k = -e[c] * e[d]
            terms.append(('+ ' if k > 0 else '- ') + f'G {c} {d}')
    s = ' '.join(terms)
    return s[2:] if s.startswith('+ ') else '-' + s[2:]


def main():
    out = [HEADER + 'module', 'public import Z3Net.TDHand', '', '@[expose] public section', '',
           '/-!', '# V14 stage S11′: `thm:D`, balance on the full steps (generated by `scripts/gen_tdbal.py`)', '',
           'For `E ∈ {±1}⁵` (binding, as `5` is odd) `2 dr(E) = −∑_{c,d} E_c G_cd E_d` (`drift_full`). The `32` full',
           'steps are written out (`full_i`), so `linarith` sees them as linear forms in the entries of `G`:',
           '* `exists_full_ge`: their mean is `−∑_c G_cc = ∑_c m_c`, so some full step has `2 dr(E) ≥ 2∑α`;',
           '* `skew_of_full_le`: if every full step has `2 dr(E) ≤ 2∑α + 1`, then the off-diagonal part is skew',
           '  (`G_cd + G_dc` is even, and `∑_E E_c E_d · 2dr(E) = −32 (G_cd + G_dc)`).', '-/', '',
           'namespace Z3NetHL.Proofs.TD', '', 'open Finset', '',
           '/-- `2 dr(E)` on a full step. -/',
           'lemma drift_full (G : Fin 5 → Fin 5 → ℤ) (E : Fin 5 → ℤ) (hE : ∀ c, E c ≠ 0) :',
           '    drift2E G E = -(∑ c, ∑ d, E c * G c d * E d) := by',
           '  unfold drift2E drc2 dotR',
           '  rw [← sum_neg_distrib]',
           '  refine sum_congr rfl fun c _ => ?_',
           '  rw [ite_eq_right_iff.mpr (fun h => absurd h (hE c)), mul_sum]',
           '  exact congrArg _ (sum_congr rfl fun d _ => by ring)', '']
    for i, e in enumerate(FULL):
        out += [f'lemma full_{i} (G : Fin 5 → Fin 5 → ℤ) :',
                f'    drift2E G {vec(e)} = {form(e)} := by',
                '  rw [drift_full G _ (by decide)]',
                '  simp [Fin.sum_univ_five]', '  ring', '']
    out += [f'lemma full_bind (E : Fin 5 → ℤ) (hE : E ∈ ([{", ".join(vec(e) for e in FULL)}] : List (Fin 5 → ℤ))) :',
            '    E ∈ bind5 ∧ ∀ c, E c ≠ 0 := by',
            '  rw [mem_bind5]',
            '  simp only [List.mem_cons, List.not_mem_nil, or_false] at hE',
            '  rcases hE with ' + ' | '.join(['rfl'] * 32) + ' <;> decide', '']
    D = [f'drift2E G {vec(e)}' for e in FULL]
    rws = 'rw [' + ', '.join(f'full_{i}' for i in range(32)) + ']'
    sumid = ' + '.join(D)
    diagsum = 'G 0 0 + G 1 1 + G 2 2 + G 3 3 + G 4 4'
    hyps = '\n  '.join(f'have h{i} := h {vec(e)} (full_bind _ (by simp)).1 (full_bind _ (by simp)).2'
                       for i, e in enumerate(FULL))
    out += [f'lemma sum_full (G : Fin 5 → Fin 5 → ℤ) :', f'    {sumid} = -32 * ({diagsum}) := by',
            f'  {rws}', '  ring', '']
    pairs = [(c, d) for c in range(5) for d in range(c + 1, 5)]
    for c, d in pairs:
        terms = []
        for i, e in enumerate(FULL):
            terms.append(('+ ' if e[c] * e[d] > 0 else '- ') + D[i])
        t = ' '.join(terms)
        t = t[2:] if t.startswith('+ ') else '-' + t[2:]
        out += [f'lemma pair_full_{c}{d} (G : Fin 5 → Fin 5 → ℤ) :', f'    {t} = -32 * (G {c} {d} + G {d} {c}) := by',
                f'  {rws}', '  ring', '']
    out += ['/-- *Balance* (`thm:D`): some full step has `2 dr(E) ≥ ∑_c m_c` (the mean over the full steps). -/',
            'lemma exists_full_ge (G : Fin 5 → Fin 5 → ℤ) (hdiag : ∀ c, G c c = -mrow G c) :',
            '    ∃ E ∈ bind5, ∑ c, mrow G c ≤ drift2E G E := by',
            '  by_contra hc',
            '  push Not at hc',
            '  have h : ∀ E ∈ bind5, (∀ c, E c ≠ 0) → drift2E G E < ∑ c, mrow G c := fun E hE _ => hc E hE',
            '  rw [Fin.sum_univ_five] at h',
            '  have d0 := hdiag 0; have d1 := hdiag 1; have d2 := hdiag 2; have d3 := hdiag 3; have d4 := hdiag 4',
            '  ' + hyps,
            '  have hs := sum_full G',
            '  linarith only [' + ', '.join(f'h{i}' for i in range(32)) + ', hs, d0, d1, d2, d3, d4]', '']
    out += ['set_option maxHeartbeats 1000000 in', '/-- *Balance* (`thm:D`): if every full step has `2 dr(E) ≤ ∑_c m_c + 1`, the off-diagonal part is skew. -/',
            'lemma skew_of_full_le (G : Fin 5 → Fin 5 → ℤ) (hodd : ∀ c d, Odd (G c d))',
            '    (hdiag : ∀ c, G c c = -mrow G c)',
            '    (h : ∀ E ∈ bind5, (∀ c, E c ≠ 0) → drift2E G E ≤ ∑ c, mrow G c + 1) :',
            '    ∀ c d, c ≠ d → G c d + G d c = 0 := by',
            '  rw [Fin.sum_univ_five] at h',
            '  have d0 := hdiag 0; have d1 := hdiag 1; have d2 := hdiag 2; have d3 := hdiag 3; have d4 := hdiag 4',
            '  ' + hyps,
            '  have hs := sum_full G']
    for c, d in pairs:
        out += [f'  have q{c}{d} : G {c} {d} + G {d} {c} = 0 := by',
                f'    obtain ⟨a, ha⟩ := hodd {c} {d}; obtain ⟨b, hb⟩ := hodd {d} {c}',
                f'    have hp := pair_full_{c}{d} G',
                f'    by_contra hne',
                f'    rcases (show G {c} {d} + G {d} {c} ≥ 2 ∨ G {c} {d} + G {d} {c} ≤ -2 by omega) with hq | hq <;>',
                '      linarith only [' + ', '.join(f'h{i}' for i in range(32)) + ', hs, hp, hq, d0, d1, d2, d3, d4]']
    out += ['  intro c d hcd',
            f'  fin_cases c <;> fin_cases d <;> {NORM} <;> first | exact absurd rfl hcd | linarith', '',
            'end Z3NetHL.Proofs.TD', '']
    open(os.path.join(L, 'Z3Net', 'TDBal.lean'), 'w').write('\n'.join(out))


if __name__ == '__main__':
    main()
