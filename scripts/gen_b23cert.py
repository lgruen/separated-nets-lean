#!/usr/bin/env python3
"""V14 stage S14′: generate the kernel-certificate modules of `thm:base23` (`Z3Net/B23Cert*.lean`): one theorem
`… = true := by decide +kernel` per check of `Z3Net/B23CertDefs.lean`, grouped into modules of a few minutes each.

Usage (from the repository root): uv run --no-project python scripts/gen_b23cert.py"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
HDR = open(os.path.join(HERE, '..', 'Z3Net', 'B23Defs.lean')).read().split('module\n')[0]
NL = {(2, 0): 7, (2, 1): 6, (2, 2): 3, (3, 0): 4, (3, 1): 5, (3, 2): 4}
SEED = {(2, 0): 9, (2, 1): 10, (2, 2): 11, (3, 0): 6, (3, 1): 7, (3, 2): 8}
MODS = {
    'B23CertNetA': [f'netChk {b} {r}' for (b, r) in [(2, 0), (2, 1), (2, 2), (3, 0)]],
    'B23CertNetB1': ['netChk 3 1'],
    'B23CertNetB2': ['netChk 3 2'],
    'B23CertC1A1': ['c1Chk 2 0'],
    'B23CertC1A2': [f'c1Chk {b} {r}' for (b, r) in [(2, 1), (2, 2), (3, 0)]],
    'B23CertC1B1': ['c1Chk 3 1'],
    'B23CertC1B2': ['c1Chk 3 2'],
    'B23CertWit': ([f'witChk 2 {m} (b23Wit 2 {m}) (b23WitU 2 {m})' for m in range(1, 9)] +
                   [f'witChk 3 {m} (b23Wit 3 {m}) (b23WitU 3 {m})' for m in range(1, 6)] +
                   [f'witChk 2 {m} (b23WitCur {m}) (b23WitCurU {m})' for m in (6, 7)]),
}
for (b, r), n in NL.items():
    MODS[f'B23CertC2_{b}{r}'] = [f'c2Chk {b} {r} {k}' for k in range(n)]


def name(t):
    p = t.split()
    if p[0] == 'witChk':
        return f'witChk_{p[1]}_{p[2]}' + ('_cur' if 'Cur' in t else '')
    return '_'.join(p)


for mod, ts in MODS.items():
    o = [HDR, 'module\npublic import Z3Net.B23CertDefs\n\n@[expose] public section\n\n',
         f'/-! # V14 stage S14′: kernel certificates of `thm:base23` ({mod}; generated by `scripts/gen_b23cert.py`) -/\n\n',
         'namespace Z3NetB23\n\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n']
    for t in ts:
        o.append(f'theorem cert_{name(t)} : {t} = true := by decide +kernel\n\n')
    o.append('end Z3NetB23\n')
    open(os.path.join(HERE, '..', 'Z3Net', mod + '.lean'), 'w').write(''.join(o))
print('ok')
