#!/usr/bin/env python3
"""Generate ChecksS1.lean: fidelity checks of the ChallengeS1 definitions against the independent
Python construction of the research notes (`skel_r1.py` (research repository) `build`: frame on the places
inf, 0, ..., s-2, graph form with depths (k+1, ..., k+1, k), gauge to the S1 skeleton row,
own blocks zeroed).
Checks:
  * the Python generator matrices satisfy `IsS1skel s p k ρ` (decided in Lean) and fail it for the
    wrong ρ (negative control), and the Python t = 0 box-rank test passes for them;
  * exact minimum `torusDist2` over all pairs (Lean, `S1_sep` integer scale) for small nets equals
    the Python value, and is >= the S1_sep bound;
  * `rhoS s p` equals floor(p^(1/s)) computed in Python;
  * λ∞ of the L2_s lattice by Python enumeration equals ρ;
  * the explicit net `S1gen` of Definition def:S1 equals (via `S1gen_eq_W`: `S1gen = S1genW Bi`
    whenever `frameBox * Bi = 1`, with the Python inverse `Bi`, both checked by `#guard`) the
    Python implementation `recipe` below of the recipe of def:S1 / prop:skelcomp(ii) (frame on the
    places inf, 0, ..., s-2, graph form by Gaussian elimination, gauge: subtract psi_l/psi_k times
    level k from the levels l < k of every full block and scale level k to rho^d/psi_k, own blocks
    zeroed), whose t = 0 property is checked by Python box ranks; muS = ceil(p / rho^(s-1)).
usage (from the repository root):  uv run python scripts/gen_checksS1.py
"""
import os, sys, itertools
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(ROOT))
from skel_r1 import build  # noqa: E402
from skel_lib import check_t0, coords, cres, frame, graph_form, net_gens, matinv  # noqa: E402

CASES = [(3, 11, 0, 2), (3, 11, 1, 2), (3, 13, 1, 2), (4, 17, 0, 2), (4, 17, 1, 2), (5, 37, 0, 2),
         (5, 37, 1, 2)]
DIST_CASES = [(3, 11, 0, 2), (3, 13, 0, 2), (3, 17, 0, 2)]


def recipe(s, p, k, rho):
    K = [k + 1] * (s - 1) + [k]
    m = sum(K)
    Phi = graph_form(frame(p, ['inf'] + list(range(s - 1)), m), K, p)
    psi = Phi[s - 1][0]
    Gm = [[1 if i == j else 0 for j in range(m)] for i in range(m)]
    for d in range(s - 1):
        r = d * (k + 1) + k
        ir = pow(psi[r], -1, p)
        Gm[r][r] = pow(rho, d + 1, p) * ir % p
        for l in range(k):
            col = d * (k + 1) + l
            Gm[r][col] = (-psi[col] * ir) % p
    Phi2 = [[[sum(row[i] * Gm[i][j] for i in range(m)) % p for j in range(m)] for row in Phi[c]]
            for c in range(s)]
    off = [c * (k + 1) for c in range(s)]
    for c in range(s):
        for row in Phi2[c]:
            for l in range(K[c]):
                row[off[c] + l] = 0
    return K, net_gens(Phi2, K, p)


def lean_mat(C):
    return "!![" + "; ".join(", ".join(str(x) for x in row) for row in C) + "]"


def lean_gens(G, s, m, p):
    return ("fun c : Fin %d => (![" % s + ", ".join(lean_mat(C) for C in G) +
            "] : Fin %d → Matrix (Fin %d) (Fin %d) (ZMod %d)) c" % (s, m, m, p))


def mind2(G, p, m):
    N = p ** m
    pts = []
    for n in itertools.product(range(p), repeat=m):
        pts.append(coords(G, list(n), p))
    best = None
    for i in range(len(pts)):
        for j in range(i + 1, len(pts)):
            d = sum(cres(N, a - b) ** 2 for a, b in zip(pts[i], pts[j]))
            if best is None or d < best:
                best = d
    return best


def iroot(p, s):
    r = int(round(p ** (1.0 / s)))
    while r ** s >= p:
        r -= 1
    while (r + 1) ** s < p:
        r += 1
    return r


def lam_inf(s, p, rho):
    B = rho + 1
    best = None
    for x in itertools.product(range(-B, B + 1), repeat=s - 1):
        z = sum(rho ** (i + 1) * x[i] for i in range(s - 1)) % p
        if z > p // 2:
            z -= p
        nrm = max([abs(v) for v in x] + [abs(z)])
        if nrm and (best is None or nrm < best):
            best = nrm
    return best


out = ["module", "public import ChallengeSplitS1E1", "meta import ChallengeSplitS1E1", "", "@[expose] public section", "",
       "/-! Generated by `scripts/gen_checksS1.py` -- do not edit by hand.",
       "Fidelity checks (NOT part of the default build) of `ChallengeS1.lean` against the independent",
       "Python construction `skel_r1.py` (research repository) (`build`: frame graph form + gauge to the S1",
       "skeleton row), see the script docstring. -/", "", "namespace Z3NetS1.Checks", "",
       "open Z3NetS1 Matrix", "",
       "instance (s p k ρ : ℕ) (C : Fin s → Matrix (Fin (s * k + (s - 1))) (Fin (s * k + (s - 1))) (ZMod p)) :",
       "    Decidable (IsS1skel s p k ρ C) := by unfold IsS1skel; infer_instance", ""]
for (s, p, k, rho) in CASES:
    K, G, _ = build(s, p, k, rho)
    m = sum(K)
    nb, bad = check_t0(G, p)
    assert not bad, (s, p, k, bad)
    _, Gbad, _ = build(s, p, k, rho + 1)
    name = "G_%d_%d_%d" % (s, p, k)
    out.append("/-! Python `skel_r1.build %d %d %d %d` (t = 0 by box ranks: %d boxes, 0 bad). -/" % (s, p, k, rho, nb))
    out.append("def %s : Fin %d → Matrix (Fin %d) (Fin %d) (ZMod %d) :=" % (name, s, m, m, p))
    out.append("  " + lean_gens(G, s, m, p))
    out.append("def %s_bad : Fin %d → Matrix (Fin %d) (Fin %d) (ZMod %d) :=" % (name, s, m, m, p))
    out.append("  " + lean_gens(Gbad, s, m, p))
    out.append("#guard decide (IsS1skel %d %d %d %d %s)" % (s, p, k, rho, name))
    out.append("#guard !decide (IsS1skel %d %d %d %d %s_bad)" % (s, p, k, rho, name))
    out.append("#guard decide (IsS1skel %d %d %d %d %s_bad)" % (s, p, k, rho + 1, name))
    out.append("")
out.append("/-! ## The explicit net of Definition `def:S1` -/")
out.append("")
out.append("/-- `framePsi` with a given matrix `Bi` in place of `(frameBox s k p)⁻¹`. -/")
out.append("def framePsiW (s k p : ℕ) (Bi : Matrix (Fin (s * k + (s - 1))) (Fin (s * k + (s - 1))) (ZMod p)) :")
out.append("    Fin (s * k + (s - 1)) → ZMod p :=")
out.append("  (fun col : Fin (s * k + (s - 1)) => if h : 0 < s then")
out.append("      ((ent (frameGen (s * k + (s - 1)) (⟨s - 1, Nat.sub_lt h Nat.one_pos⟩ : Fin s)) k col : ℤ) : ZMod p) else 0) ᵥ* Bi")
out.append("")
out.append("/-- `gaugeS1` with `framePsiW`. -/")
out.append("def gaugeS1W (s k p ρ : ℕ) (Bi : Matrix (Fin (s * k + (s - 1))) (Fin (s * k + (s - 1))) (ZMod p)) :")
out.append("    Matrix (Fin (s * k + (s - 1))) (Fin (s * k + (s - 1))) (ZMod p) :=")
out.append("  fun r col =>")
out.append("    if (r : ℕ) % (k + 1) = k ∧ (r : ℕ) / (k + 1) + 1 < s then")
out.append("      (if col = r then ((ρ ^ ((r : ℕ) / (k + 1) + 1) : ℕ) : ZMod p) * (framePsiW s k p Bi r)⁻¹")
out.append("       else if (col : ℕ) / (k + 1) = (r : ℕ) / (k + 1) ∧ (col : ℕ) < r then")
out.append("         -(framePsiW s k p Bi col) * (framePsiW s k p Bi r)⁻¹ else 0)")
out.append("    else if col = r then 1 else 0")
out.append("")
out.append("/-- `S1gen` with `Bi` in place of `(frameBox s k p)⁻¹`. -/")
out.append("def S1genW (s p k ρ : ℕ) (Bi : Matrix (Fin (s * k + (s - 1))) (Fin (s * k + (s - 1))) (ZMod p))")
out.append("    (c : Fin s) : Matrix (Fin (s * k + (s - 1))) (Fin (s * k + (s - 1))) (ZMod p) :=")
out.append("  fun i col =>")
out.append("    if (i : ℕ) < depth s k c then (if (col : ℕ) = off k c + i then 1 else 0)")
out.append("    else if blk s k col = (c : ℕ) then 0")
out.append("    else (((frameGen (s * k + (s - 1)) c).map (Int.cast : ℤ → ZMod p)) * Bi * gaugeS1W s k p ρ Bi) i col")
out.append("")
out.append("/-- If `B · Bi = 1` for the box matrix `B = frameBox s k p`, then `S1gen = S1genW Bi`; so the")
out.append("`#guard`s below (`B · Bi = 1` and `S1genW Bi = Python`) identify `S1gen` with the Python net. -/")
out.append("theorem S1gen_eq_W (s p k ρ : ℕ) (Bi : Matrix (Fin (s * k + (s - 1))) (Fin (s * k + (s - 1))) (ZMod p))")
out.append("    (h : frameBox s k p * Bi = 1) : S1gen s p k ρ = S1genW s p k ρ Bi := by")
out.append("  have hB : (frameBox s k p)⁻¹ = Bi := Matrix.inv_eq_right_inv h")
out.append("  unfold S1gen S1genW gaugeS1 gaugeS1W framePsi framePsiW")
out.append("  rw [hB]")
out.append("")
for (s, p, k, rho) in [(3, 11, 0, 2), (3, 11, 1, 2), (3, 13, 1, 2), (4, 17, 0, 2), (4, 17, 1, 2), (5, 37, 0, 2)]:
    K, G = recipe(s, p, k, rho)
    m = sum(K)
    nb, bad = check_t0(G, p)
    assert not bad, (s, p, k, bad)
    name = "R_%d_%d_%d" % (s, p, k)
    _, Gb, _ = build(s, p, k, rho)
    same = (G == Gb)
    out.append("/-! Python `recipe %d %d %d %d` (t = 0 by box ranks: %d boxes, 0 bad; %s `skel_r1.build`). -/" %
               (s, p, k, rho, nb, "equal to" if same else "differs (other gauge solution) from"))
    out.append("def %s : Fin %d → Matrix (Fin %d) (Fin %d) (ZMod %d) :=" % (name, s, m, m, p))
    out.append("  " + lean_gens(G, s, m, p))
    Brows = [frame(p, ['inf'] + list(range(s - 1)), m)[c][j] for c in range(s) for j in range(K[c])]
    Bi = matinv(Brows, p)
    out.append("def Bi_%d_%d_%d : Matrix (Fin %d) (Fin %d) (ZMod %d) := %s" % (s, p, k, m, m, p, lean_mat(Bi)))
    out.append("#guard decide (frameBox %d %d %d * Bi_%d_%d_%d = 1)" % (s, k, p, s, p, k))
    out.append("#guard decide (S1genW %d %d %d %d Bi_%d_%d_%d = %s)" % (s, p, k, rho, s, p, k, name))
    out.append("#guard decide (IsS1skel %d %d %d %d %s)" % (s, p, k, rho, name))
    out.append("")
out.append("/-! `muS s p ρ = ⌈p / ρ^(s-1)⌉` (Python). -/")
mus = [(s, p, r) for s in (3, 4, 5) for p in (11, 13, 29, 37, 101, 997) for r in (1, 2, 3, 5)]
out.append("#guard (%s).map (fun (x : ℕ × ℕ × ℕ) => muS x.1 x.2.1 x.2.2) = %s" % (
    "[" + ", ".join("(%d, %d, %d)" % x for x in mus) + "]",
    str([-(-p // r ** (s - 1)) for (s, p, r) in mus])))
out.append("")
out.append("/-- Exact minimum of `torusDist2` over all pairs (Lean) = Python value; `S1_sep` bound. -/")
out.append("def minD2 {s m p : ℕ} [NeZero p] (C : Fin s → Matrix (Fin m) (Fin m) (ZMod p)) : ℕ :=")
out.append("  let pts := (List.finRange (p ^ m)).map fun t =>")
out.append("    digPoint p m C (fun j : Fin m => ((t : ℕ) / p ^ (j : ℕ) : ℕ))")
out.append("  (pts.zipIdx.flatMap fun (x, i) => (pts.drop (i + 1)).map fun y => torusDist2 (p ^ m) x y).foldl min (p ^ (2 * m) * s)")
for (s, p, k, rho) in DIST_CASES:
    K, G, _ = build(s, p, k, rho)
    m = sum(K)
    d2 = mind2(G, p, m)
    bound = (rho - 1) ** 2 * p ** (2 * ((s - 1) * (k + 1) - 1))
    assert d2 >= bound
    name = "G_%d_%d_%d" % (s, p, k)
    if (s, p, k, rho) not in CASES:
        out.append("def %s : Fin %d → Matrix (Fin %d) (Fin %d) (ZMod %d) :=" % (name, s, m, m, p))
        out.append("  " + lean_gens(G, s, m, p))
    out.append("#guard minD2 %s = %d  -- Python exact; S1_sep bound %d, c = %.4f" %
               (name, d2, bound, (d2 ** 0.5) / p ** m * p ** (m / s)))
out.append("")
out.append("/-! `rhoS s p = ⌊p^(1/s)⌋` (Python integer root), primes 2^s < p < 400, s = 2..6. -/")
from sympy import primerange  # noqa: E402
for s in range(2, 7):
    ps = [p for p in primerange(2 ** s + 1, 400)]
    out.append("#guard (%s).map (rhoS %d) = %s" % (str(ps), s, str([iroot(p, s) for p in ps])))
out.append("")
out.append("/-! λ∞ of the L2_s lattice by Python enumeration (equals ρ = ρ_s(p), cf. `L2s_min`, `L2s_attained`):")
for (s, p) in [(3, 11), (3, 29), (3, 127), (4, 17), (4, 83), (5, 37), (5, 251)]:
    r = iroot(p, s)
    lam = lam_inf(s, p, r)
    assert lam == r, (s, p, lam, r)
    out.append("  (s, p) = (%d, %d): ρ = %d, λ∞ = %d" % (s, p, r, lam))
out.append("-/")
out.append("")
out.append("end Z3NetS1.Checks")
open(os.path.join(ROOT, "ChecksS1.lean"), "w").write("\n".join(out) + "\n")
print("wrote ChecksS1.lean")
