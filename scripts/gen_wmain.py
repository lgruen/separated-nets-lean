#!/usr/bin/env python3
"""V14 stage S12′: generate `QUNetsM3/WMain.lean`, the Solution-side restatements of the compared theorems of
stage S12′ (`scripts/v14_delta.py`, `NEW`): the statement texts are taken verbatim from `v14_delta.py`, the `sorry` is
replaced by the proof term below.

Usage (from the repository root): uv run --no-project python scripts/gen_wmain.py"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import v14_delta as D  # noqa: E402

L = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
HEADER = open(os.path.join(L, 'QUNetsM3', 'TCMain.lean')).read().split('module\n')[0]
HEADER = HEADER.replace(
    'Main statements of entry TwoCoset (same statements as the theorem block of\n`ChallengeTwoCoset.lean`). '
    'Generated by `scripts/gen_twocoset.py`.',
    'Solution side of the statements added in V14 stage S12′ (`sec:wnet`: `prop:wnet`, `lem:wwrap`, `prop:wfamily`,\n'
    '`rem:wstar`; the `𝒲_p` sentence of `rem:shiftshared`). Generated by `scripts/gen_wmain.py`.')

PROOF = {
    'W_layer': '⟨w_layer hodd r, fun hr => w_layer_tau hodd hr⟩',
    'W_net': 'w_net hp hp5',
    'W_cells': 'w_cells hp b hb',
    'W_freeJitter': 'w_freeJitter hp hp53 g f hg hgx hgy hgz hf n n\' hn hn\' hne t',
    'W_sep': 'w_sep hp hp53 x x\' hx hx\' hne t',
    'W_sep_real': 'w_sep_real hp hp53',
    'W_bound': '⟨fun _ _ h h\' => cW_mono h h\', fun _ h => cW_gt1 h, fun _ h => cW_gt66 h, cW_values⟩',
    'W_pair': 'w_pair hp hp53',
    'W_pair_lt': 'w_pair_lt hp hp53',
    'W_delta': 'w_delta hp hp53',
    'W_limit': 'w_limit',
    'W_exact': ('⟨fun _ hp h17 h89 => wexact_cover hp h17 h89,\n'
                '    fun q hq => ⟨(wexact_tab q hq).1, (wexact_tab q hq).2, w_exact_delta q hq⟩⟩'),
    'W_four': 'w_four',
    'W_least': 'w_least',
    'W_wrap': 'wwrap hp hp5 u E d k',
    'Wfam_star': 'wfam_star',
    'Wfam_one': '⟨wfam_FpW hp hp5 u, wfam_delta hp u T⟩',
    'Wfam_two': 'wfam_two h0 h1',
    'Wfam_three_tau': 'wfam_three_tau τ',
    'Wfam_three': 'wfam_three_net hp hp5 u T',
    'Wstar_net': 'wstar_net hp hp5',
    'Wstar_rho': 'wstar_rho hp',
    'Wstar_eps': 'wstar_eps hp h17',
    'Wstar_bound': 'wstar_bound hp h17',
    'Wstar_limit': 'wstar_limit',
    'Wstar_thresholds': 'wstar_thresholds',
    'Wstar_ahead': 'wstar_ahead hp h',
    'W_shift': 'w_shift hp hp53 τ hxy hab x x\' hx hx\' hne t',
}


def main():
    new = [x for x in D.NEW if D.STAGE[x['name']] == 'S12′']
    body = []
    for x in new:
        short = x['name'].split('.')[-1]
        text = x['body']
        assert text.rstrip().endswith(':= by\n  sorry') or text.rstrip().endswith(':= by\n  sorry'.strip()), short
        stmt = text.rstrip()
        assert stmt.endswith('sorry')
        stmt = stmt[:-len('sorry')].rstrip()
        assert stmt.endswith(':= by')
        stmt = stmt[:-len(' by')]
        body += [x['doc'], stmt, '  ' + PROOF[short], '']
    assert len(new) == len(PROOF), (len(new), len(PROOF))
    out = [HEADER + 'module', 'public import QUNetsM3.WStar', 'public import QUNetsM3.WFour', '',
           '@[expose] public section', '',
           '/-!', '# Solution side of the statements added in V14 stage S12′ (`sec:wnet`)', '',
           'The compared theorems of `scripts/v14_delta.py` (stage S12′, `NEW`), restated by name with the same '
           'statements as in',
           '`QUNets/Statements/Large.lean` and `QUNets/Statements/DGS.lean` (`W_shift`). Proof modules: '
           '`QUNetsM3/WWrap.lean`',
           '(`lem:wwrap`), `WNet.lean`, `WCore.lean`, `WSep.lean`, `WPair.lean`, `WReduce.lean`, `WExactCore.lean`, '
           '`WExact.lean`,',
           '`WFour.lean` (`prop:wnet`, the shifts), `WFamCert.lean`, `WFamTwo.lean`, `WFamThree.lean`, `WFamOne.lean` '
           '(`prop:wfamily`),',
           '`WStar.lean` (`rem:wstar`).', '-/', '',
           'namespace QUNetsM3', '', 'open Matrix Filter Topology', ''] + body + ['end QUNetsM3', '']
    open(os.path.join(L, 'QUNetsM3', 'WMain.lean'), 'w').write('\n'.join(out))
    print('wrote QUNetsM3/WMain.lean,', len(new), 'theorems')


if __name__ == '__main__':
    main()
