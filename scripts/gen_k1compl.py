#!/usr/bin/env python3
"""V14 stage S15′: generate `Z3Net/K1ComplData.lean` (the integer `t = 0` completions of the frameless layers of
`prop:k1designs`(2) and their kernel checks) from `scripts/k1compl_data.json` (integer completions A5, A6a, A6b) and
`../k1sep_audit/free_completions.json` (the audited per-prime completions of the layer `free_s6_sm7` = `k1Free6b` at
p = 11, 13, 17, 19). Before writing, every check is rerun here in exact integer arithmetic.

Usage (from the repository root): uv run --no-project python scripts/gen_k1compl.py"""
import json, os
L = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
F5 = [[-2, 1, -1, -2, -1], [-1, -2, -2, 2, -1], [-1, 1, -1, -1, 2], [-2, 1, -2, -2, 1], [-1, -2, 1, 1, -2]]
F6a = [[-3, -3, 2, -1, 2, 1], [1, -3, 2, 1, 3, -2], [1, -2, -3, 3, -1, -1], [2, 3, 1, -2, -1, 1],
       [-3, -2, 1, 1, -3, 2], [-1, -1, 3, 2, 2, -3]]
F6b = [[-4, 1, 3, -1, 2, 4], [-2, -4, 1, -1, 1, 3], [-4, -2, -4, 4, 1, -2], [-2, 4, -2, -4, -4, -2],
       [1, -3, 3, 1, -5, 2], [-1, 4, 4, -2, 1, -5]]
E6 = [2, 3, 5, 7, 11, 13, 17, 23, 31]


def comps(s, m):
    if s == 1:
        yield (m,)
        return
    for a in range(m + 1):
        for r in comps(s - 1, m - a):
            yield (a,) + r


def det(M):
    n = len(M)
    if n == 0:
        return 1
    return sum((-1) ** j * M[0][j] * det([r[:j] + r[j + 1:] for r in M[1:]]) for j in range(n) if M[0][j])


def boxdets(F, D):
    s = len(F)
    C = [[[1 if j == c else 0 for j in range(s)], list(F[c])] + [[0 if d == c else D[c][r][d] for d in range(s)]
                                                                  for r in range(s - 2)] for c in range(s)]
    return [det(sum((C[c][:d[c]] for c in range(s)), [])) for d in comps(s, s)]


def smooth(v, S):
    v = abs(v)
    if v == 0:
        return False
    for p in S:
        while v % p == 0:
            v //= p
    return v == 1


data = json.load(open(os.path.join(L, 'scripts', 'k1compl_data.json')))
fc = json.load(open(os.path.join(L, '..', 'k1sep_audit', 'free_completions.json')))['free_s6_sm7']
assert fc['F0'] == F6b
A5, A6a, A6b = data['A5'], data['A6a'], data['A6b']
assert all(smooth(v, [2, 3, 5]) for v in boxdets(F5, A5))
assert all(smooth(v, E6) for v in boxdets(F6a, A6a))
assert all(smooth(v, [2, 3, 5, 7, 11, 13, 17, 19]) for v in boxdets(F6b, A6b))
PP = [11, 13, 17, 19]
E = {p: fc['completions'][str(p)] for p in PP}
for p in PP:
    assert all(v % p for v in boxdets(F6b, E[p])), p


def lit(D):
    return '![' + ', '.join('![' + ', '.join('![' + ', '.join(str(x) for x in row) + ']' for row in Dc) + ']'
                            for Dc in D) + ']'


HEADER = open(os.path.join(L, 'Z3Net', 'K1Compl.lean')).read().split('module\n')[0]
o = [HEADER, 'module\npublic import Z3Net.K1Compl\n\n@[expose] public section\n\n',
     '/-!\n# V14 stage S15′: the `t = 0` completions of `prop:k1designs`(2) (data and kernel checks)\n\n',
     'Generated by `scripts/gen_k1compl.py` from `scripts/k1compl_data.json` and the audited per-prime completions of\n',
     '`k1sep_audit/free_completions.json` (research repository). Kernel `decide +kernel` (no `native_decide`): every box minor\n',
     '(`lem:box`, all compositions of `s`) of the integer completion `A5` of `k1Free5` has only the prime factors\n',
     '`2, 3, 5`; of `A6a` (`k1Free6a`) only those of `𝓔₆ = {2, 3, 5, 7, 11, 13, 17, 23, 31}`; of `A6b` (`k1Free6b`)\n',
     'only `2, 3, 5, 7, 11, 13, 17, 19`; and the per-prime completions `E6b p` of `k1Free6b` have every box minor prime\n',
     'to `p` for `p = 11, 13, 17, 19`.\n-/\n\nnamespace Z3NetF.Proofs.K1Compl\n\n']
o.append(f'/-- Integer completion of `k1Free5` (box minors only with the primes `2, 3, 5`). -/\n'
         f'def A5 : Fin 5 → Fin 3 → Fin 5 → ℤ := {lit(A5)}\n\n')
o.append(f'/-- Integer completion of `k1Free6a` (box minors only with the primes of `𝓔₆`). -/\n'
         f'def A6a : Fin 6 → Fin 4 → Fin 6 → ℤ := {lit(A6a)}\n\n')
o.append(f'/-- Integer completion of `k1Free6b` (box minors only with the primes `2, …, 19`). -/\n'
         f'def A6b : Fin 6 → Fin 4 → Fin 6 → ℤ := {lit(A6b)}\n\n')
for p in PP:
    o.append(f'/-- The completion of `k1Free6b` modulo `{p}` (`free_completions.json`, `free_s6_sm7`). -/\n'
             f'def E6b{p} : Fin 6 → Fin 4 → Fin 6 → ℤ := {lit(E[p])}\n\n')
pre = 'set_option maxHeartbeats 0 in\nset_option maxRecDepth 100000 in\n'
o.append(pre + 'theorem chk5 : (compList 5 5).all (fun d => strip [2, 3, 5] (boxDetM k1Free5 A5 d).natAbs = 1) = true := by\n  decide +kernel\n\n')
o.append(pre + 'theorem chk6a : (compList 6 6).all (fun d =>\n    strip [2, 3, 5, 7, 11, 13, 17, 23, 31] (boxDetM k1Free6a A6a d).natAbs = 1) = true := by\n  decide +kernel\n\n')
o.append(pre + 'theorem chk6b : (compList 6 6).all (fun d =>\n    strip [2, 3, 5, 7, 11, 13, 17, 19] (boxDetM k1Free6b A6b d).natAbs = 1) = true := by\n  decide +kernel\n\n')
for p in PP:
    o.append(pre + f'theorem chk6b{p} : (compList 6 6).all (fun d => boxDetM k1Free6b E6b{p} d % {p} ≠ 0) = true := by\n  decide +kernel\n\n')
o.append('end Z3NetF.Proofs.K1Compl\n')
open(os.path.join(L, 'Z3Net', 'K1ComplData.lean'), 'w').write(''.join(o))
print('ok')
