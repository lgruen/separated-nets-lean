#!/usr/bin/env python3
"""Generate ChecksU.lean: fidelity checks of the ChallengeU definitions against the independent
Python construction of the research notes (`sgg_design.py` (research repository): uniform_design + build_net, which
builds Definition N_s literally: raw frame graph form O G^{-1} over Q, Toeplitz gauge Q_d^k g_d,
residual gauge U'_d, beta_n solved by linear algebra), reduced mod q.
usage (from the repository root):  uv run --with numpy python scripts/gen_checksU.py
"""
import os, sys
from fractions import Fraction as Fr
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(ROOT))
from sgg_design import uniform_design, build_net  # noqa: E402
from sgg_lib import reading_matrix, frac_det, INF  # noqa: E402

CASES = [(3, 4, 3), (3, 5, 4), (4, 5, 2), (4, 9, 2), (4, 5, 4), (5, 7, 2), (5, 25, 2), (6, 5, 2)]


def gens(s, k):
    places, F, lam, Up, a = uniform_design(s)
    Phip = build_net(places, F, lam, Up, k)
    m = s * k
    out = []
    for c in range(s):
        rows = []
        for j in range(k):
            r = [Fr(0)] * m
            r[c * k + j] = Fr(1)
            rows.append(r)
        for orow in range(m - k):
            r = []
            for d in range(s):
                r += Phip[c, d][orow]
            rows.append(r)
        out.append(rows)
    return out, a


def red(x, q):
    x = Fr(x)
    return (x.numerator * pow(x.denominator, -1, q)) % q


lines = ["module", "public import ChallengePPInvU", "meta import ChallengePPInvU", "", "@[expose] public section", "",
         "/-! Generated by `scripts/gen_checksU.py` -- do not edit by hand.",
         "Fidelity check (NOT part of the default build): the Challenge generator matrices",
         "`UGen s q k c` (graph form, index = cell vector) equal, entry by entry, the matrices of the",
         "independent Python construction `sgg_design.py` (research repository) (`uniform_design`, `build_net`:",
         "Definition N_s built literally -- raw frame graph form `O G⁻¹` over `ℚ`, gauge",
         "`λ_c = λ'_c Q_c^(-k)`, `U_d = Q_d^k Toep(g_d) U'^(k)_d` with `β_n` solved by linear algebra),",
         "reduced mod `q`; the constants `a_c`, `a_s` agree with the note's table; and frame box minors",
         "(`boxMatrix (frameGen m) d`) equal the exact determinants of the independent Python frame",
         "`sgg_lib.reading_matrix` (signed, same row order). -/", "",
         "namespace Z3NetU.Checks", "", "open Z3NetU Matrix", ""]
done_a = set()
for (s, q, k) in CASES:
    G, a = gens(s, k)
    if s not in done_a:
        done_a.add(s)
        lines.append(f"#guard (List.finRange {s}).map (acoef {s}) = {[int(x) for x in a]}")
        lines.append(f"#guard aU {s} = {int(max(a))}")
    for c in range(s):
        rows = "; ".join(", ".join(str(red(x, q)) for x in r) for r in G[c])
        lines.append(f"#guard UGen {s} {q} {k} {c} = !![{rows}]")
# frame box minors: exact (signed) determinant from the independent Python frame, rows in the
# order coordinate 0 (INF, top coefficients) first, then the finite places 0, 1, ..., s-2
FRAME = [(4, 6, (1, 2, 2, 1)), (4, 6, (2, 0, 3, 1)), (4, 5, (0, 1, 1, 3)), (5, 6, (1, 1, 2, 1, 1)),
         (5, 6, (0, 2, 0, 2, 2)), (5, 5, (2, 0, 1, 1, 1))]
lines.append("")
for (s_, m_, d_) in FRAME:
    places = [INF] + list(range(s_ - 1))
    Cs = [reading_matrix(a, m_) for a in places]
    M = [Cs[c][j] for c in range(s_) for j in range(d_[c])]
    det = frac_det(M)
    assert det.denominator == 1
    lines.append(f"#guard (boxMatrix (frameGen (s := {s_}) {m_}) ![{', '.join(map(str, d_))}]).det = {int(det)}")
lines += ["", "end Z3NetU.Checks", ""]
open(os.path.join(ROOT, "ChecksU.lean"), "w").write("\n".join(lines))
print("wrote", len(lines), "lines")
