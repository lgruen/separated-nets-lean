"""Generate ChecksCpp.lean: kernel-checked equalities between the Challenge generator matrices
(reduced mod q) and the matrices printed by the C++ reference `cpp/genz3net.h` (research repository)
(`genz3net_test mats q m ek|two`).  Usage: gen_checks_cpp.py <path-to-genz3net_test>"""
import subprocess, sys

exe = sys.argv[1]
P_CASES = [(2, 1), (2, 2), (2, 3), (2, 4), (3, 1), (3, 2), (3, 3), (3, 4), (4, 1), (4, 2), (4, 3),
           (4, 4), (5, 1), (5, 2), (5, 3), (5, 4), (6, 2), (6, 3), (7, 2), (7, 3), (7, 4), (8, 2),
           (8, 3), (11, 2), (11, 3), (13, 2), (16, 2), (16, 3)]
Q_CASES = [(11, 2), (11, 3), (11, 4), (13, 2), (13, 3), (13, 4), (17, 2), (19, 2), (19, 3),
           (19, 4), (23, 3)]

def mats(q, m, var):
    out = subprocess.run([exe, "mats", str(q), str(m), var], capture_output=True, text=True,
                         check=True).stdout.split("\n")
    assert out[0].split() == [str(q), str(m), "3"]
    res = []
    for c in range(3):
        e = list(map(int, out[1 + c].split()))
        assert len(e) == m * m
        res.append("!![" + "; ".join(", ".join(map(str, e[i * m:(i + 1) * m])) for i in range(m)) + "]")
    return res

lines = ["module", "public import Checks", "", "@[expose] public section", "",
         "/-! Generated by `scripts/gen_checks_cpp.py` -- do not edit.",
         "Kernel-checked: the Challenge generator matrices mod q equal those of the C++ reference",
         "`cpp/genz3net.h` (research repository) (variant `ek` = 𝒫_{k,q}, variant `two` at p ≥ 11 = 𝒬_{k,p}). -/",
         "", "namespace Z3Net.ChecksCpp", "", "open Z3Net Z3Net.Checks Matrix", ""]
for q, k in P_CASES:
    for c, lit in enumerate(mats(q, 3 * k, "ek")):
        lines.append(f"example : (PGen {k} {c}).map (Int.cast : ℤ → ZMod {q}) = {lit} := by")
        lines.append("  decide +kernel")
for p, k in Q_CASES:
    for c, lit in enumerate(mats(p, 3 * k, "two")):
        lines.append(f"example : (QGen {k} {c}).map (Int.cast : ℤ → ZMod {p}) = {lit} := by")
        lines.append(f"  rw [QGen_eq{k}]; decide +kernel")
PT_CASES = [(4, 2), (7, 2), (3, 3), (2, 4), (16, 2)]
for q, k in PT_CASES:
    m = 3 * k
    out = subprocess.run([exe, "pts", str(q), str(m), "ek"], capture_output=True, text=True,
                         check=True).stdout.split("\n")
    n = q ** m
    for i in sorted({0, 1, q - 1, q, n // 3, n // 2 + 7, (2 * n) // 3 + 1, n - 2, n - 1}):
        x, y, z = out[1 + i].split()
        lines.append(f"example : Ppoint {q} {k} (idx {q} {m} {i}) = ![{x}, {y}, {z}] := by decide +kernel")
lines += ["", "end Z3Net.ChecksCpp", ""]
open("ChecksCpp.lean", "w").write("\n".join(lines))
print(len(P_CASES), "P cases,", len(Q_CASES), "Q cases,", len(PT_CASES), "point cases")
