#!/usr/bin/env python3
"""V14 stage S15′: generate `Z3Net/S15Restate.lean`, the Solution-side restatements of the compared theorems of stage
S15′ (`scripts/v14_delta.py`, `NEW` with stage `S15′`): the statement texts verbatim, `sorry` replaced by the proof
term in `PROOF`.

Usage (from the repository root): uv run --no-project python scripts/gen_s15main.py"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import v14_delta as D  # noqa: E402

L = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
HEADER = open(os.path.join(L, 'Z3Net', 'K1Compl.lean')).read().split('module\n')[0]
P = 'Proofs.'
K = 'Proofs.K1Compl.'
PROOF = {
    'Z3NetKN.ppsep_shift': P + 'ppsep_shift_core p r k T hp hk R Rg hcert C hC τ v w hvw',
    'Z3NetKN.KN1_sep_shift': P + 'KN1_sep_shift_core p T R hmem k hk C hC τ v w hvw',
    'Z3NetKN.KN2_sep_shift': P + 'KN2_sep_shift_core p T R hmem k hk C hC τ v w hvw',
    'Z3NetDGS.dgs_pp': P + 'dgs_pp_core p m hp hp5 hp31 hm',
    'Z3NetDGS.dgs_family_pp': P + 'dgs_family_pp_core p hp hp5 hp31',
    'Z3NetDGS.dgs_family_b23': P + 'dgs_family_b23_core b hb',
    'Z3NetDGS.dgs_family_all': P + 'dgs_family_all_core p hp',
    'Z3NetF.k1designs_free5_net': K + 'free5_net q hq',
    'Z3NetF.k1designs_free6a_net': K + 'free6a_net q hq',
    'Z3NetF.k1designs_free6b_net': K + 'free6b_net q hq',
    'Z3NetF.k1designs_frame5_cauchy': '⟨' + K + 'places5_ok, fun c d h => ' + K + 'frame5_cauchy c d h⟩',
}
ents = [x for x in D.NEW if D.STAGE[x['name']] == 'S15′']
assert set(PROOF) == {x['name'] for x in ents}
o = [HEADER + 'module\npublic import Z3Net.PPShift\npublic import Z3Net.DGSAll\npublic import Z3Net.K1ComplMain\n\n'
     '@[expose] public section\n\n'
     '/-!\n# Solution side of the statements added in V14 stage S15′ (`rem:ppshift`, `rem:dgsfinite`, `prop:k1designs`)\n\n'
     'The compared theorems of `scripts/v14_delta.py` (stage S15′), restated by name with the same statements as in\n'
     '`QUNets/Statements/{Appendix,DGS,Deficit}.lean`; the proofs are in the imported modules. Generated by\n'
     '`scripts/gen_s15main.py`.\n-/\n']
cur = None
for x in ents:
    ctx = (x['ns'], x['opens'])
    if ctx != cur:
        if cur:
            o.append(f'end {cur[0]}\n')
        o.append(f'\nnamespace {x["ns"]}\n\n' + ''.join(op + '\n' for op in x['opens']) + '\n')
        cur = ctx
    body = x['body'].replace(':= by\n  sorry', ':=\n  ' + PROOF[x['name']])
    assert ':=\n  ' in body, x['name']
    o.append(x['doc'] + '\n' + body + '\n\n')
o.append(f'end {cur[0]}\n')
open(os.path.join(L, 'Z3Net', 'S15Restate.lean'), 'w').write(''.join(o))
print(len(ents), 'theorems')
