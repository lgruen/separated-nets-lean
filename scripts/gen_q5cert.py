#!/usr/bin/env python3
"""V14 stage S11′: generate the kernel scans of `prop:half5` (`Z3Net/Q5ScanR2_*.lean`, `Z3Net/Q5ScanHk_*.lean`):
for every prime 37 ≤ p < 200 the exact `lem:R2` check `(2p²)² < ∑_c (2b_c)²` on every step `0 ≠ E ∈ {-2,…,2}⁵`,
for every prime 53 ≤ p < 200 the exact `prop:Hk`(1) check `(2p)² < ∑_c (2b_c)²`, and at `p = 200` the starred
(monotone) checks of both (`Z3Net/Q5ScanTail.lean`). The checkers are `Z3Net/Q5CertDefs.lean`.
Usage (from the repository root): uv run --no-project python scripts/gen_q5cert.py"""
import os

L = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
HEADER = open(os.path.join(L, 'Z3Net', 'TDCert.lean')).read().split('module\n')[0]


def primes(a, b):
    return [p for p in range(a, b) if p > 1 and all(p % k for k in range(2, int(p ** .5) + 1))]


R2P = primes(37, 200)
HKP = primes(53, 200)
DEC = '(by decide +kernel)'
FV = f'(forall_vals5 {DEC} {DEC} {DEC} {DEC} {DEC})'


def module(name, title, body):
    out = [HEADER + 'module', 'public import Z3Net.Q5CertDefs', '', '@[expose] public section', '',
           f'/-! # V14 stage S11′: `prop:half5`, {title} (generated by `scripts/gen_q5cert.py`) -/', '',
           'namespace Z3NetHL.Proofs.Q5', '', 'open Z3NetHL Z3NetHL.Proofs', '',
           'set_option maxRecDepth 100000', 'set_option maxHeartbeats 0', ''] + body + ['end Z3NetHL.Proofs.Q5', '']
    open(os.path.join(L, 'Z3Net', name + '.lean'), 'w').write('\n'.join(out))


def chunks(xs, n):
    k = (len(xs) + n - 1) // n
    return [xs[i * k:(i + 1) * k] for i in range(n) if xs[i * k:(i + 1) * k]]


def main():
    mods = []
    for i, ps in enumerate(chunks(R2P, 5)):
        body = []
        for p in ps:
            T = (2 * p * p) ** 2
            body += [f'theorem r2_{p} : ∀ E ∈ halfSteps 5, ({T} : ℤ) < ∑ c, bR2 {p} F2star D1star E c ^ 2 :=',
                     f'  r2_of_chk {p} {T} {FV}', '']
        name = f'Q5ScanR2_{i}'
        module(name, f'the exact `lem:R2` scans at p = {ps[0]}…{ps[-1]}', body)
        mods.append(name)
    for i, ps in enumerate(chunks(HKP, 3)):
        body = []
        for p in ps:
            T = (2 * p) ** 2
            body += [f'theorem hk_{p} : ∀ E ∈ halfSteps 5, ({T} : ℤ) < ∑ c, bOpt2 {p} (fun _ => F2star) E (fun _ => 0) c ^ 2 :=',
                     f'  hk_of_chk {p} {T} {FV}', '']
        name = f'Q5ScanHk_{i}'
        module(name, f'the exact `prop:Hk`(1) scans at p = {ps[0]}…{ps[-1]}', body)
        mods.append(name)
    body = [f'theorem r2s_200 : ∀ E ∈ halfSteps 5, ({(2 * 200 * 200) ** 2} : ℤ) < ∑ c, bR2s 200 (decide ((∑ d, E d) % 2 = 1))',
            '    (E c) (dotR F2star E c) (dotR D1star E c) ^ 2 :=',
            f'  r2s_of_chk 200 _ {FV}', '',
            f'theorem hks_200 : ∀ E ∈ halfSteps 5, ({(2 * 200) ** 2} : ℤ) < ∑ c, bHks 200 (decide ((∑ d, E d) % 2 = 1))',
            '    (E c) (dotR F2star E c) ^ 2 :=',
            f'  hks_of_chk 200 _ {FV}', '']
    module('Q5ScanTail', 'the starred (monotone) checks at p = 200', body)
    mods.append('Q5ScanTail')
    print('R2 primes', len(R2P), 'Hk primes', len(HKP), 'modules', mods)


if __name__ == '__main__':
    main()
