#!/usr/bin/env python3
"""V14 stage S16′ (`cor:skelreach`, `rem:wshift`; audit items `thm:col`(1), `lem:drift`(2), `cor:dgs`(4), `rem:accounting`; `rem:shiftparity`): generate `Z3Net/S16Restate.lean`, the Solution-side restatements of the compared theorems of stage
S16′ (`scripts/v14_delta.py`, `NEW` with stage `S16′`): the statement texts verbatim, `sorry` replaced by the proof
term in `PROOF`.

Usage (from the repository root): uv run --no-project python scripts/gen_s16main.py"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import v14_delta as D  # noqa: E402

L = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
HEADER = open(os.path.join(L, 'Z3Net', 'S15Restate.lean')).read().split('module\n')[0].replace('revision 15.7', 'revision 15.10')
P = 'Proofs.'
PROOF = {
    'Z3NetF.skelreach_iff': P + 'SkReach.skelreach_iff_core p r hr A β g o',
    'Z3NetF.skelreach_nec': P + 'SkReach.skelreach_nec_core p r k hr hk A β g o Φ hΦ hnet',
    'QUNetsM3.TC_shift': 'tc_shift hp hp41 τ hyz x x\' hx hx\' hne t',
    'QUNetsM3.W_wrap_one': 'wwrap_one hp hp5 u E d k',
    'Z3NetC.col_boxMinor_int': '⟨' + P + 'colZ_lift q, ' + P + 'colZ_box3 q⟩',
    'Z3NetC.drift_excess': P + 'drift_excess_core w ℓ hw3 i hR n',
    'Z3NetDGS.dgs_S1_floor': P + 'dgs_S1_floor_core s p k ρ hs hp hρ hps τ',
    'Z3NetHL.acct_LB2': P + 'Acct.acct_LB2_core F2 D1 hodd hΛ',
    'Z3NetB23.shiftparity_parity': P + 'Parity.parity_core hL hev C h0 sA sB',
    'Z3NetB23.shiftparity_first_even': P + 'Parity.first_even_core hL C h0 sA sB hpos',
    'Z3NetB23.shiftparity_dichotomy': P + 'Parity.dichotomy_core hL h0 h',
    'Z3NetB23.shiftparity_floor_iff': P + 'Parity.floor_iff_core hm₀ hseq hfz',
    'Z3NetB23.shiftparity_tendsto': P + 'Parity.tendsto_core hm₀ hseq hinf ε hε',
    'Z3NetHL.acct_LBHk': P + 'Acct.acct_LBHk_core F2 hodd hΛ',
}
ents = [x for x in D.NEW if D.STAGE[x['name']] == 'S16′']
assert set(PROOF) == {x['name'] for x in ents}
o = [HEADER + 'module\npublic import Z3Net.SkReach\npublic import QUNetsM3.TCShift\npublic import QUNetsM3.WWrapOne\n'
     'public import Z3Net.ColZMinor\npublic import Z3Net.DGSRho\npublic import Z3Net.AcctTwo\npublic import Z3Net.B23Parity\npublic import Z3Net.AcctHk\n\n'
     '@[expose] public section\n\n'
     '/-!\n# Solution side of the statements added in V14 stage S16′ (`cor:skelreach`, `rem:wshift`, `thm:col`, '
     '`lem:drift`, `cor:dgs`, `rem:accounting`, `rem:shiftparity`)\n\n'
     'The compared theorems of `scripts/v14_delta.py` (stage S16′), restated by name with the same statements as in\n'
     '`QUNets/Statements/Skeleton.lean` (`cor:skelreach`), `QUNets/Statements/Large.lean` (`rem:wshift`),\n'
     '`QUNets/Statements/Dim3.lean` (`thm:col`), `QUNets/Statements/Deficit.lean` (`lem:drift`), `QUNets/Statements/DGS.lean`\n'
     '(`cor:dgs`), `QUNets/Statements/Split.lean` (`rem:accounting`) and `QUNets/Statements/Base23.lean`\n'
     '(`rem:shiftparity`); the proofs are\n'
     'in the imported modules. Generated by `scripts/gen_s16main.py`.\n-/\n']
cur = None
for x in ents:
    ctx = (x['ns'], x['opens'])
    if ctx != cur:
        if cur:
            o.append(f'end {cur[0]}\n')
        o.append(f'\nnamespace {x["ns"]}\n\n' + ''.join(op + '\n' for op in x['opens']) + '\n')
        cur = ctx
    body = x['body'].replace(':= by\n  sorry', ':=\n  ' + PROOF[x['name']])
    assert ':=\n  ' in body, x['name']
    o.append(x['doc'] + '\n' + body + '\n\n')
o.append(f'end {cur[0]}\n')
open(os.path.join(L, 'Z3Net', 'S16Restate.lean'), 'w').write(''.join(o))
print(len(ents), 'theorems')
