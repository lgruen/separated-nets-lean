#!/usr/bin/env python3
"""V14 stage S14′: generate `Z3Net/B23Restate.lean`, the Solution-side restatements of the compared theorems of stage
S14′ (`scripts/v14_delta.py`, `NEW` with stage `S14′`): the statement texts verbatim, `sorry` replaced by the proof
term in `PROOF`.

Usage (from the repository root): uv run --no-project python scripts/gen_s14main.py"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import v14_delta as D  # noqa: E402

L = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
HEADER = open(os.path.join(L, 'Z3Net', 'B23Defs.lean')).read().split('module\n')[0]
P = 'Proofs.'
PROOF = {
    'Z3NetB23.lift_net': P + 'lift_net C σ sA sB hP hadm',
    'Z3NetB23.lift_exists': P + 'lift_exists C σ hP D hD',
    'Z3NetB23.liftsep': P + 'liftsep hD h v w hvw',
    'Z3NetB23.shiftcert_a': P + 'shiftcert_a hD h τ v w hvw',
    'Z3NetB23.vcirc_eq_iInf': P + 'vcirc_eq_iInf L hL C₀',
    'Z3NetB23.shiftcert_b': P + 'shiftcert_b C',
    'Z3NetB23.b23_seed': P + 'b23_seed_core b r hb',
    'Z3NetB23.b23_lift': P + 'b23_lift_core b r k hb hr hk',
    'Z3NetB23.b23_vcirc': 'by\n    have e : b23Vcert b r = b23V b r := by\n      rcases hb with rfl | rfl <;> interval_cases r <;> rfl\n    rw [e]; exact ' + P + 'b23_vcirc_core b r hb hr',
    'Z3NetB23.base23_net': P + 'base23_net_core b hb h σ',
    'Z3NetB23.base23_exists': P + 'base23_exists_core b hb m hm',
    'Z3NetB23.base23_everyshift': P + 'base23_everyshift_core b hb h τ v w hvw',
    'Z3NetB23.base23_everyshift_base': P + 'base23_base_core b hb h τ v w hvw',
    'Z3NetB23.base23_witcur': P + 'b23_witcur_core m hm',
    'Z3NetB23.base23_shifted': P + 'base23_shifted_core b r hb hr v₁ hcert h v w hvw',
}
ents = [x for x in D.NEW if D.STAGE[x['name']] == 'S14′']
assert set(PROOF) == {x['name'] for x in ents}
o = [HEADER + 'module\npublic import Z3Net.B23Main\npublic import Z3Net.B23Consts\n\n@[expose] public section\n\n'
     '/-!\n# Solution side of the statements added in V14 stage S14′ (`sec:base23`)\n\n'
     'The compared theorems of `scripts/v14_delta.py` (stage S14′), restated by name with the same statements as in\n'
     '`QUNets/Statements/Base23.lean`; the proofs are in the imported modules. Generated by `scripts/gen_s14main.py`.\n-/\n']
cur = None
for x in ents:
    ctx = (x['ns'], x['opens'])
    if ctx != cur:
        if cur:
            o.append(f'end {cur[0]}\n')
        o.append(f'\nnamespace {x["ns"]}\n\n' + ''.join(op + '\n' for op in x['opens']) + '\n')
        cur = ctx
    body = x['body'].replace(':= by\n  sorry', ':=\n  ' + PROOF[x['name']])
    assert ':=\n  ' in body, x['name']
    o.append(x['doc'] + '\n' + body + '\n\n')
o.append(f'end {cur[0]}\n')
open(os.path.join(L, 'Z3Net', 'B23Restate.lean'), 'w').write(''.join(o))
print(len(ents), 'theorems')
