#!/usr/bin/env python3
"""V14 stage S13′: generate `Z3Net/S13Main.lean`, the Solution-side restatements of the compared theorems of stage S13′
(`scripts/v14_delta.py`, `NEW` with stage `S13′`): the statement texts are taken verbatim from `v14_delta.py`, the
`sorry` is replaced by the proof term in `PROOF` (keyed by the full name). Theorems are grouped by namespace, in the
order of `v14_delta.py`; each group repeats the `open`s of its entries.

Usage (from the repository root): uv run --no-project python scripts/gen_s13main.py"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import v14_delta as D  # noqa: E402

L = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
HEADER = open(os.path.join(L, 'QUNetsM3', 'WMain.lean')).read().split('module\n')[0]
HEADER = HEADER.replace(
    'Solution side of the statements added in V14 stage S12′ (`sec:wnet`: `prop:wnet`, `lem:wwrap`, `prop:wfamily`,\n'
    '`rem:wstar`; the `𝒲_p` sentence of `rem:shiftshared`). Generated by `scripts/gen_wmain.py`.',
    'Solution side of the statements added in V14 stage S13′ (`rem:projlines`, `rem:accounting`, the link of\n'
    '`digitalPtS` to `def:dshift`). Generated by `scripts/gen_s13main.py`.')
assert 'S13′' in HEADER

# proof modules imported by the restatement module
IMPORTS = [
    'QUNetsM3.WShiftLink',
    'Z3Net.ProjLines',
    'Z3Net.ProjSep',
    'Z3Net.ProjPSep',
    'Z3Net.AcctMain',
]

# full name -> proof term
PROOF = {
    'QUNetsM3.digitalPtS_eq_dshiftPt': 'digitalPtS_eq_dshiftPt_core p C τ x',
    'Z3NetF.projlines_frame': 'Proofs.frame_rowRel_iff inf x hx hm hab g',
    'Z3NetF.projlines': 'Proofs.projlines_core inf x F lam Ur β hx hres hodd hsk hab g',
    'Z3NetF.projlines_zmod': 'Proofs.projlines_zmod_core inf x F lam Ur β ψ hx hres hodd hsk hab g',
    'Z3NetF.projlines_box': 'Proofs.projlines_box_core C hab hm h1 h2',
    'Z3NetF.rowScale_box': 'Proofs.rowScale_box_core C r ρ d hd',
    'Z3NetF.rowScale_net': 'Proofs.rowScale_net_core C r ρ hρ',
    'Z3NetF.tsk_net_rowScale': 'Proofs.tsk_net_rowScale_core inf x F lam Ur β ψ hx hres r ρ hρ',
    'Z3NetF.rowScale_rowRel': 'Proofs.rowScale_rowRel_core C r ρ ha h',
    'Z3NetF.Ss_sep_rowScale': 'Proofs.Ss_sep_rowScale_core hs hq hk hL hLk F Φ h1 h2 B hBq hB hr ρ v w hvw',
    'Z3NetF.D_sep_rowScale':
        'Proofs.D_sep_rowScale_core hs ψ k hk inf x hx F lam Ur β hres hβ α h0 hdiag hdom ha hq hr ρ v w hvw',
    'Z3Net.projlines_P': 'Z3NetF.Proofs.P_rowRel_core k hk hab',
    'Z3Net.P_net_rowScale': 'Z3NetF.Proofs.P_net_rowScale_core q k hk r ρ hρ',
    'Z3Net.P_sep_rowScale': 'Sep.P_sep_rowScale_core q k r hq hk hr ρ v w hvw',
    'Z3NetA.A_sep_rowScale': 'Proofs.A_sep_rowScale_core s q k hs hq hqa hk hr ρ v w hvw',
    'Z3NetHL.sepN_spec': 'Proofs.Acct.sepN_spec_core p hp X',
    'Z3NetHL.ell2_eq_halfEllInf': 'Proofs.Acct.ell2_eq_halfEllInf_core F2 E c',
    'Z3NetHL.acct_upper': 'Proofs.Acct.acct_upper_core F2 D hodd hΛ',
    'Z3NetHL.acct_lower': 'Proofs.Acct.acct_lower_core F2 D hodd hdet',
    'Z3NetHL.acct_main': 'Proofs.Acct.acct_main_core F2 D hodd hdet hΛ ε hε',
    'Z3NetHL.acct_liminf': 'Proofs.Acct.acct_liminf_core F2 D hodd hdet hΛ',
    'Z3NetHL.acct_exact': 'Proofs.Acct.acct_exact_core F2 D hodd hdet hΛ heq',
    'Z3NetHL.acct_qstar': 'Proofs.Acct.acct_qstar_core',
    'Z3NetHL.acct_counterexample': 'Proofs.Acct.acct_counterexample_core',
}


def main():
    new = [x for x in D.NEW if D.STAGE[x['name']] == 'S13′']
    assert len(new) == len(PROOF), (len(new), len(PROOF), sorted(set(x['name'] for x in new) ^ set(PROOF)))
    body = []
    cur = None
    for x in new:
        ns = x['ns']
        short = x['name'][len(ns) + 1:]
        assert x['name'] == ns + '.' + short
        stmt = x['body'].rstrip()
        assert stmt.endswith('sorry'), short
        stmt = stmt[:-len('sorry')].rstrip()
        assert stmt.endswith(':= by'), short
        stmt = stmt[:-len(' by')]
        if (ns, x['opens']) != cur:
            if cur is not None:
                body += [f'end {cur[0]}', '']
            body += [f'namespace {ns}', ''] + list(x['opens']) + ['']
            cur = (ns, x['opens'])
        body += [x['doc'], stmt, '  ' + PROOF[x['name']], '']
    if cur is not None:
        body += [f'end {cur[0]}', '']
    out = [HEADER + 'module'] + [f'public import {m}' for m in IMPORTS] + [
        '', '@[expose] public section', '',
        '/-!', '# Solution side of the statements added in V14 stage S13′', '',
        'The compared theorems of `scripts/v14_delta.py` (stage S13′, `NEW`), restated by name with the same statements as',
        'in `QUNets/Statements/*.lean`; the proofs are in the imported modules.', '-/', ''] + body
    open(os.path.join(L, 'Z3Net', 'S13Main.lean'), 'w').write('\n'.join(out))
    print('wrote Z3Net/S13Main.lean,', len(new), 'theorems')


if __name__ == '__main__':
    main()
