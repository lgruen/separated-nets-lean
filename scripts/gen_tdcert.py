#!/usr/bin/env python3
"""V14 stage S11′: generate the kernel runs of the `thm:D` enumeration (`Z3Net/TDCert0.lean` … `TDCert5.lean`, one
`decide +kernel` theorem per candidate row 0) and `Z3Net/TDCertAll.lean` (the candidate list of row 0 and the
assembly). The checker itself is `Z3Net/TDCert.lean`. Usage (from the repository root):
uv run --no-project python scripts/gen_tdcert.py"""
import os

L = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
HEADER = open(os.path.join(L, 'Z3Net', 'TDCert.lean')).read().split('module\n')[0]
VALS = [-3, -1, 1, 3]
NMOD = 6


def mk(c, x, y, z, w):
    o, r, k = [x, y, z, w], [], 0
    for d in range(5):
        if d == c:
            r.append(-3)
        else:
            r.append(o[k])
            k += 1
    return r


def cols(a, b):
    return [c for c in range(5) if c not in (a, b)]


def pair_ok(a, b, ra, rb):
    c, d, e = cols(a, b)
    return (ra[c] * rb[d] != ra[d] * rb[c] and ra[c] * rb[e] != ra[e] * rb[c] and ra[d] * rb[e] != ra[e] * rb[d])


def cand(c):
    row4 = [1, 1, 1, 1, -1]
    out = []
    for x in VALS:
        for y in VALS:
            for z in VALS:
                for w in VALS:
                    r = mk(c, x, y, z, w)
                    if any(abs(t) == 3 for t in (x, y, z, w)) and pair_ok(c, 4, r, row4):
                        out.append(r)
    return out


def lit(r):
    return '⟨' + ', '.join(str(x) for x in r) + '⟩'


def main():
    c0 = cand(0)
    assert len(c0) == 96
    per = (len(c0) + NMOD - 1) // NMOD
    for m in range(NMOD):
        body = [HEADER + 'module', 'public import Z3Net.TDCert', '', '@[expose] public section', '',
                f'/-! # V14 stage S11′: `thm:D`, kernel runs {m * per}–{min(len(c0), (m + 1) * per) - 1} of the '
                'enumeration (generated by `scripts/gen_tdcert.py`) -/', '',
                'namespace Z3NetHL.Proofs.TD', '', 'set_option maxRecDepth 100000', 'set_option maxHeartbeats 0', '']
        for i in range(m * per, min(len(c0), (m + 1) * per)):
            body.append(f'theorem slice_{i} : chkTop {lit(c0[i])} = true := by decide +kernel')
            body.append('')
        body += ['end Z3NetHL.Proofs.TD', '']
        open(os.path.join(L, 'Z3Net', f'TDCert{m}.lean'), 'w').write('\n'.join(body))
    body = [HEADER + 'module'] + [f'public import Z3Net.TDCert{m}' for m in range(NMOD)]
    body += ['', '@[expose] public section', '',
             '/-! # V14 stage S11′: `thm:D`, the enumeration assembled (generated by `scripts/gen_tdcert.py`)', '',
             'The `96` candidates of row `0` and the kernel run for each (`Z3Net/TDCert0.lean` … `TDCert5.lean`). -/', '',
             'namespace Z3NetHL.Proofs.TD', '', 'set_option maxRecDepth 100000', '',
             'theorem cand0_eq : cand 0 = [' + ',\n    '.join(lit(r) for r in c0) + '] := by',
             '  decide +kernel', '',
             '/-- **The enumeration**: for every candidate row `0` the checker succeeds. -/',
             'theorem chkTop_cand0 : ∀ r ∈ cand 0, chkTop r = true := by',
             '  rw [cand0_eq]',
             '  intro r hr',
             '  simp only [List.mem_cons, List.not_mem_nil, or_false] at hr',
             '  rcases hr with ' + ' | '.join(['rfl'] * len(c0)),
             '  exacts [' + ', '.join(f'slice_{i}' for i in range(len(c0))) + ']', '',
             'end Z3NetHL.Proofs.TD', '']
    open(os.path.join(L, 'Z3Net', 'TDCertAll.lean'), 'w').write('\n'.join(body))


if __name__ == '__main__':
    main()
