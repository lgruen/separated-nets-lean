# half_tab_t0: deeper rows of the s = 6, 8 witnesses (`eis_link_t0_witnesses.json,` (research repository)
# coordinate-major: deep[c][j] = deeper row j+1 of coordinate c), checked box by box over ZMod p
# by fraction-free elimination (Z3Net/HalfCertFF.lean).

T0 = {6: [211, 1009, 10007, 1000003], 8: [1009, 10007, 1000003]}

def comps(m, s):
    if s == 1:
        yield (m,); return
    for a in range(m + 1):
        for r in comps(m - a, s - 1):
            yield (a,) + r

def nonsing(rows, p):
    A = [[x % p for x in r] for r in rows]; n = len(A)
    for i in range(n):
        piv = next((r for r in range(i, n) if A[r][i]), None)
        if piv is None:
            return False
        A[i], A[piv] = A[piv], A[i]; a = A[i][i]
        for r in range(i + 1, n):
            b = A[r][i]; A[r] = [(a*x - b*y) % p for x, y in zip(A[r], A[i])]
    return True

def comps_count(m, k):
    from math import comb
    return comb(m + k - 1, k - 1)

LEAF = 120   # max boxes per `decide +kernel` theorem (kernel memory grows with the slice)

def split_tree(s, pref):
    """post-order list of (prefix, is_leaf) covering all compositions with this prefix."""
    rem = s - sum(pref)
    if comps_count(rem, s - len(pref)) <= LEAF or len(pref) >= s - 1:
        return [(tuple(pref), True)]
    out = []
    for a in range(rem + 1):
        out += split_tree(s, pref + [a])
    return out + [(tuple(pref), False)]

def t0_data(s, p):
    import json
    from fractions import Fraction
    W = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    '../../eis_link_t0_witnesses.json')))
    w = W[f'{s},{p}']; deep = w['deep']; M2 = M[s]
    assert [[int(2 * Fraction(x)) for x in r] for r in w['M']] == M2
    assert len(deep) == s and all(len(deep[c]) == s - 2 for c in range(s))
    gen = [[[1 if j == c else 0 for j in range(s)], M2[c]] + [deep[c][r] for r in range(s - 2)]
           for c in range(s)]
    assert all(nonsing([gen[c][j] for c in range(s) for j in range(d[c])], p)
               for d in comps(s, s)), (s, p)
    tab = '![' + ',\n    '.join('![' + ', '.join('![' + ', '.join(str(x) for x in row) + ']'
                                               for row in deep[c]) + ']' for c in range(s)) + ']'
    return (f'/-- Deeper rows of the `s = {s}`, `p = {p}` witness: `W{s}_{p} c j` is row `j + 1` of\n'
            f'coordinate `c`. -/\n'
            f'def W{s}_{p} : Fin {s} → Fin {s - 2} → Fin {s} → ℤ :=\n  {tab}\n\n'
            f'def D{s}_{p} (c : Fin {s}) (r : ℕ) (d : Fin {s}) : ℤ :=\n'
            f'  if h : 1 ≤ r ∧ r ≤ {s - 2} then W{s}_{p} c ⟨r - 1, by omega⟩ d else 0\n')

def node_thm(s, p, pref, leaf):
    nm = lambda pr: f'c{s}_{p}' + ''.join(f'_{a}' for a in pr)
    args = ' '.join(str(a) for a in pref)
    head = f'theorem {nm(pref)} : ck{s}_{len(pref)} {p} M{s}h D{s}_{p} {args} = true'.replace('  ', ' ')
    if leaf:
        return head + ' := by decide +kernel'
    K = s - sum(pref) + 1
    cases = '\n'.join(f'    | {a}, _ => {nm(pref + (a,))}' for a in range(K))
    return (head + ' := by\n'
            f'  unfold ck{s}_{len(pref)}\n'
            f'  exact all_range_of _ fun i hi => match i, hi with\n{cases}\n'
            f'    | n + {K}, h => absurd h (by omega)')

def t0_files(s, p, parts):
    """parts: list of (file name, predicate on prefixes); the last file gets the root + net."""
    tree = split_tree(s, [])
    hdr = HDR.replace('{what}', f'`t = 0` of the `s = {s}`, `p = {p}` witness')
    prev = 'Z3Net.HalfCertFF'
    for idx, (name, pred) in enumerate(parts):
        out = [hdr.replace('import Z3Net.HalfCertDefs', 'import ' + prev)]
        if idx == 0:
            out.append(t0_data(s, p))
        last = idx == len(parts) - 1
        for pref, leaf in tree:
            if (pref == () and last) or (pref != () and pred(pref)):
                out.append(node_thm(s, p, pref, leaf))
        if last:
            out.append(f'\ntheorem net{s}_{p} : IsNet0 {s} {p} ({s} * 1) (GFpoint {s} {p} 1 (halfPhi {s} {p} M{s}h D{s}_{p})) :=\n'
                       f'  net_of_ck{s} {p} (by norm_num) (by norm_num) M{s}h D{s}_{p} c{s}_{p}\n')
        out.append('end Z3NetHL.Proofs\n')
        write(f'Z3Net/{name}.lean', '\n'.join(out))
        prev = 'Z3Net.' + name

def main_t0():
    os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
    for p in T0[6]:
        t0_files(6, p, [(f'HalfCertW6_{p}', lambda pr: True)])
    for p in T0[8]:
        t0_files(8, p, [(f'HalfCertW8_{p}a', lambda pr: pr[0] == 0),
                        (f'HalfCertW8_{p}b', lambda pr: pr[0] != 0)])

if __name__ == '__main__':
    if sys.argv[1:] == ['t0']:
        main_t0()
    else:
        main()
